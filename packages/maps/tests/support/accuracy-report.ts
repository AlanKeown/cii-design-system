import type {
  AccuracyFixtureSet,
  CapturedAccuracyCase
} from './accuracy-cases.ts';

type ReportInput = {
  browser: Pick<AccuracyFixtureSet['browser'], 'version'>;
  oracle: Pick<
    AccuracyFixtureSet['oracle'],
    'image' | 'postgresVersion' | 'postgisFullVersion' | 'gridProbes'
  >;
  fixtures: readonly (Pick<CapturedAccuracyCase, 'id' | 'residualAtCapture'> & {
    kind: string;
    method: string;
  })[];
};

/** Generate the human-readable baseline from exactly the reviewed JSON fixture data. */
export function renderAccuracyReport(set: ReportInput): string {
  const projection = set.fixtures.filter(
    (entry) => entry.kind === 'projection'
  );
  const datum = set.fixtures.filter(
    (entry) => entry.kind === 'datum-comparison'
  );
  return `# PostGIS accuracy baseline

Generated by \`npm run generate:accuracy-fixtures -w @cii/maps\`. Do not edit numerical results by hand. Exact coordinates, source SRIDs, target SRIDs, operation text and tolerances are in \`postgis-accuracy.json\`.

The oracle is a disposable container pinned to \`${set.oracle.image}\`. It runs with no host ports, persistent storage or outbound network. These results describe this reference environment; they do not audit the production Supabase or self-hosted servers.

PostgreSQL: ${set.oracle.postgresVersion}. Browser: proj4 ${set.browser.version}. Coordinate order: x/y throughout; CRS84 uses PostGIS SRID 4326 with longitude-first point construction.

\`PostGIS_Full_Version()\`:

\`\`\`text
${set.oracle.postgisFullVersion}
\`\`\`

## Projection agreement

${projection.length} same-datum cases cover Web Mercator, GDA94 and GDA2020 MGA zones 54–59, off-meridian points, NSW Lambert, and inverse projected-to-geographic conversions. Projected-coordinate comparisons use a 0.001 metre Euclidean tolerance; geographic comparisons use 1e-8 degrees. These are numerical agreement thresholds at the listed samples, not survey accuracy guarantees or a proof across an entire CRS area of use.

## Datum comparisons

Residuals are Euclidean distances between browser and oracle outputs in the **target CRS units**. Web Mercator projected metres are not ground metres. Values below are rounded; the JSON retains the full values. These differences are characterised, never accepted by widening the projection tolerances.

| Case | Method | Residual in target metres |
| --- | --- | ---: |
${datum.map((entry) => `| ${entry.id} | ${entry.method} | ${entry.residualAtCapture.toFixed(6)} |`).join('\n')}

\`ST_Transform\` chooses an operation automatically using the installed PROJ database and available resources. Its selected operation is not introspected here, so automatic fixtures have no claimed pipeline identifier. The explicit cases use \`ST_TransformPipeline\` with the checked-in EPSG:8048 parameters, boundary axis swaps removed for x/y, followed by the named target projection. The GDA2020-aligned Web Mercator case remains an ensemble approximation; no realisation or epoch model is applied.

In this environment the default GDA94-to-Web-Mercator output agrees numerically with the browser while the explicitly GDA2020-aligned output differs. Numerical agreement with a default web-map transform therefore does not establish precise datum alignment. The browser service continues to report \`DATUM_DIFFERENCE\` and ensemble limitations.

## Grid operation probes

Each probe attempts a required grid operation at longitude 151.21, latitude -33.87, with PROJ networking disabled. This records whether that operation can run at the sample coordinate; it is not an exhaustive filesystem inventory or proof that automatic transformations chose a grid.

| Grid | Usable at Sydney | Failure SQLSTATE |
| --- | --- | --- |
${set.oracle.gridProbes.map((probe) => `| ${probe.name} | ${probe.usableAtSydney ? 'yes' : 'no'} | ${probe.errorState ?? 'none'} |`).join('\n')}

## Validation and regeneration

- \`npm run test:unit -w @cii/maps\` checks the captured oracle values, datum residuals, warning codes, metadata and case catalog without Docker.
- \`npm run test:accuracy -w @cii/maps\` starts a fresh pinned oracle, checks live coordinates, versions, grid probes and browser residuals against the reviewed baseline, then removes only its own container. CI runs this as a separate job.
- \`npm run generate:accuracy-fixtures -w @cii/maps\` deliberately replaces the JSON and this report from a fresh oracle. Review both before accepting a baseline change.

PostGIS/PROJ configuration, installed grids and automatic operation selection can differ elsewhere. Spike S7 still requires per-target-server pipeline/grid audits, and installed-grid comparisons remain outstanding. The separate \`transforms.json\` fixtures retain the local PROJ CLI projection-only baseline.
`;
}
