import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { writeFileSync } from 'node:fs';
import type { CrsDef } from '../src/crs/types.ts';

// PROJ is an authoring tool only. Consumers and CI use the checked-in output.
const codes = [
  'EPSG:3857',
  'EPSG:4326',
  'OGC:CRS84',
  'EPSG:7844',
  'EPSG:8058',
  'EPSG:4283',
  ...Array.from({ length: 6 }, (_, i) => `EPSG:${7854 + i}`),
  ...Array.from({ length: 5 }, (_, i) => `EPSG:${28354 + i}`),
  'EPSG:6738'
];
const run = promisify(execFile);
const definitions: CrsDef[] = [];
for (const code of codes) {
  const info = JSON.parse(
    (await run('projinfo', [code, '-o', 'PROJJSON', '-q'])).stdout
  ) as {
    name: string;
    type: string;
    bbox: {
      west_longitude: number;
      south_latitude: number;
      east_longitude: number;
      north_latitude: number;
    };
    base_crs?: { id: { authority: string; code: number } };
  };
  const bbox = info.bbox;
  definitions.push({
    code,
    name: info.name,
    proj4: (await run('projinfo', [code, '-o', 'PROJ', '-q'])).stdout.trim(),
    units: info.type === 'ProjectedCRS' ? 'metres' : 'degrees',
    projected: info.type === 'ProjectedCRS',
    geographicBase: info.base_crs
      ? `${info.base_crs.id.authority}:${info.base_crs.id.code}`
      : code,
    areaOfUse: [
      bbox.west_longitude,
      bbox.south_latitude,
      bbox.east_longitude,
      bbox.north_latitude
    ],
    ...(code === 'EPSG:3857'
      ? {
          tileMatrix: {
            origin: [-Math.PI * 6378137, Math.PI * 6378137] as const,
            resolutions: Array.from(
              { length: 25 },
              (_, zoom) => (2 * Math.PI * 6378137) / 256 / 2 ** zoom
            )
          }
        }
      : {})
  });
}
writeFileSync(
  new URL('../src/crs/definitions.ts', import.meta.url),
  `// Generated by scripts/generate-crs.ts using projinfo. Do not edit by hand.\n` +
    `import type { CrsDef } from './types.ts';\n\nexport const definitions: readonly CrsDef[] = ${JSON.stringify(definitions, null, 2)};\n`
);
